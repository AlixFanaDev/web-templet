#!/usr/bin/env python3
"""Fetch author + licence metadata for every placeholder photo and write
docs/IMAGE_CREDITS.md (required attribution for the CC images in public/assets).

Parses the ITEMS table straight out of fetch-placeholders.py (so it never
triggers a re-download), queries the Commons imageinfo API for each file and
renders a markdown credit roll.

Run from repo root:
    python3 scripts/credits.py
"""
import ast
import html
import json
import os
import re
import sys
import time
import urllib.error
import urllib.parse
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
FETCH = os.path.join(HERE, "fetch-placeholders.py")
OUT = os.path.join(HERE, "..", "docs", "IMAGE_CREDITS.md")
UA = "MustiTarguiSiteBuilder/1.0 (placeholder credits)"
API = "https://commons.wikimedia.org/w/api.php"


def read_items():
    """Extract the ITEMS literal from fetch-placeholders.py without executing it."""
    tree = ast.parse(open(FETCH, encoding="utf-8").read())
    for node in ast.walk(tree):
        if isinstance(node, ast.Assign):
            if any(getattr(t, "id", None) == "ITEMS" for t in node.targets):
                return ast.literal_eval(node.value)
    raise SystemExit("ITEMS not found in fetch-placeholders.py")


def strip_html(value: str) -> str:
    text = re.sub(r"<[^>]+>", "", value or "")
    text = html.unescape(text)
    return re.sub(r"\s+", " ", text).strip()


def fetch_meta(file_title: str):
    qs = urllib.parse.urlencode({
        "action": "query",
        "titles": file_title,
        "prop": "imageinfo",
        "iiprop": "extmetadata",
        "format": "json",
    })
    req = urllib.request.Request(f"{API}?{qs}", headers={"User-Agent": UA})
    for attempt in range(4):
        try:
            with urllib.request.urlopen(req, timeout=60) as resp:
                data = json.load(resp)
            break
        except urllib.error.HTTPError as exc:
            if exc.code == 429 and attempt < 3:
                time.sleep(20 * (attempt + 1))
                continue
            raise
    page = next(iter(data["query"]["pages"].values()))
    meta = page.get("imageinfo", [{}])[0].get("extmetadata", {})

    def get(key):
        return strip_html(meta.get(key, {}).get("value", ""))

    return {
        "artist": get("Artist") or "Unknown",
        "licence": get("LicenseShortName") or "See source",
        "credit": get("Credit"),
    }


def main() -> None:
    items = read_items()
    rows = []
    for name, path, _bucket, _crop in items:
        file_name = urllib.parse.unquote(path.rsplit("/", 1)[-1])
        title = f"File:{file_name}"
        try:
            meta = fetch_meta(title)
        except Exception as exc:  # keep the roll complete even if one query fails
            meta = {"artist": f"UNRESOLVED ({exc})", "licence": "?", "credit": ""}
        rows.append((name, file_name, meta))
        print(f"{name}: {meta['artist']} — {meta['licence']}")
        time.sleep(2.0)  # stay well under the Commons rate limit

    lines = [
        "# Image credits",
        "",
        "All photography in `public/assets/` is placeholder imagery from",
        "[Wikimedia Commons](https://commons.wikimedia.org/), downloaded and",
        "cropped by `scripts/fetch-placeholders.py`. Every image is served in",
        "JPEG + WebP + AVIF variants generated by `scripts/build-responsive.py`.",
        "",
        "Replace these files (keeping the same file names) with final",
        "production photography — see README → “Placeholder assets” for",
        "suggested Unsplash search terms.",
        "",
        "| Slot | File on Commons | Author | Licence |",
        "| --- | --- | --- | --- |",
    ]
    for name, file_name, meta in rows:
        url = "https://commons.wikimedia.org/wiki/" + urllib.parse.quote(file_name.replace(" ", "_"))
        lines.append(
            f"| `{name}` | [{file_name}]({url}) | {meta['artist']} | {meta['licence']} |"
        )
    lines += [
        "",
        "Licences: images are under CC BY, CC BY-SA or CC0 as marked above;",
        "attribution text is preserved here as required by the respective",
        "licence. When in doubt, check each file’s description page (linked).",
        "",
    ]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print(f"\nWrote {os.path.normpath(OUT)} ({len(rows)} entries)")


if __name__ == "__main__":
    main()
